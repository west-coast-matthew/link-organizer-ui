import { useEffect, useState } from 'react'
import { motion } from 'motion/react'
import type { LinkItem } from '../types'
import { isAwaitingThumbnail, useLinkThumbnail } from '../services/link-mgmnt-queries'
import { LoadingStatePanel } from './LoadingStatePanel'
import { Icon, hostOf } from './ui'

/** Turns an image blob into a URL an <img> can show, and frees it when the blob goes away. */
function useObjectUrl(blob: Blob | null | undefined) {
  const [url, setUrl] = useState<string>()
  useEffect(() => {
    if (!blob) {
      setUrl(undefined)
      return
    }
    const next = URL.createObjectURL(blob)
    setUrl(next)
    return () => URL.revokeObjectURL(next)
  }, [blob])
  return url
}

/**
 * The 16:9 preview at the top of a link card. Thumbnails are generated by the server
 * after a link is created, so a new link shows the loading panel and checks again
 * every 30 seconds until the image arrives.
 */
export function LinkThumbnail({ link }: { link: Pick<LinkItem, 'id' | 'url' | 'createdAt'> }) {
  const { data } = useLinkThumbnail(link)
  const src = useObjectUrl(data)
  const waiting = !data && isAwaitingThumbnail(link)

  return (
    <div className="thumb">
      {src ? (
        <a href={link.url} target="_blank" rel="noreferrer" tabIndex={-1} aria-hidden="true">
          <motion.img
            className="thumb__img"
            src={src}
            alt=""
            width={640}
            height={360}
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            transition={{ duration: 0.3 }}
          />
        </a>
      ) : waiting ? (
        <LoadingStatePanel className="thumb__panel" title="Generating preview…" message="Checking again every 30 seconds." />
      ) : (
        <div className="thumb__empty" aria-hidden="true">
          <Icon name="globe" size={22} />
          <span>{hostOf(link.url)}</span>
        </div>
      )}
    </div>
  )
}
